function buildProfile(id: FighterId): FighterProfile {
  const cfg = ROSTER_DISPLAY_CONFIG[id];
  const spec = GAMEPLAY_SPECS[id];
  return {
    id,
    name: cfg.displayName,
    fullName: cfg.fullName,
    party: cfg.factionLabel,
    titleTag: cfg.titleTag,
    accent: cfg.accent,
    isBoss: cfg.isBoss,
    modelUrl: cfg.modelUrl,
    portraitUrl: cfg.portraitUrl,
    voiceLines: {
      intro: cfg.introLine,
      super: cfg.superLine,
      win: cfg.winLine,
      introAudio: cfg.voiceAudio.intro,
      superAudio: cfg.voiceAudio.super,
      winAudio: cfg.voiceAudio.win,
    },
    look: spec.look,
    walkFwd: spec.walkFwd,
    walkBack: spec.walkBack,
    jumpV: spec.jumpV,
    jumpVx: spec.jumpVx,
    damageMul: spec.damageMul,
    reachMul: spec.reachMul,
    modelHeight: spec.modelHeight,
    danceIntro: spec.danceIntro,
    moveNames: cfg.moveNames,
    superName: cfg.superName,
    superDesc: cfg.superDesc,
    introLine: cfg.introLine,
    winLine: cfg.winLine,
    dance: {
      label: cfg.danceLabel,
      colors: spec.danceColors,
    },
  };
}

