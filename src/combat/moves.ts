export function moveTotalFrames(move: MoveDefinition): number {
  return move.startup + move.active + move.recovery;
}

export function selectGroundedAttack(button: 'punch' | 'kick' | 'grab', crouching: boolean, pressingForward: boolean): MoveId {
  if (button === 'grab') return 'grab';
  if (crouching) return button === 'punch' ? 'lowJab' : 'sweep';
  if (pressingForward) return button === 'punch' ? 'special1' : 'special2';
  return button === 'punch' ? 'jab' : 'kick';
}

export function resolveNextChainMove(
  fighterId: FighterId,
  currentMove: MoveDefinition,
  button: 'punch' | 'kick' | 'grab',
): MoveId | null {
  if (button === 'grab') return null;
  const override = CHARACTER_CHAIN_OVERRIDES[fighterId]?.[currentMove.id]?.[button];
  return override ?? currentMove.chains?.[button] ?? null;
}

export function getMoveReach(fighterId: FighterId, moveId: MoveId): number {
  return Math.max(0.52, CHARACTER_REACH_OVERRIDES[fighterId]?.[moveId] ?? BASE_MOVES[moveId].reach);
}
